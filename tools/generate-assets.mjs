// Regenerates the bundled icons (src/icons/generated.ts) and the backdrop SVGs (backdrops/).
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const { DEVICES, buildInline, CSS } = require("./design/icons.cjs");
const { BACKDROPS } = require("./design/backdrops.cjs");

const icons = { glow: {}, crisp: {} };
for (const mode of ["glow", "crisp"])
  for (const d of DEVICES) for (const s of d.states) icons[mode][`${d.key}/${s}`] = buildInline(mode, d, s);
const sets = Object.fromEntries(DEVICES.map((d) => [d.key, d.states]));

writeFileSync(
  "src/icons/generated.ts",
  `// Generated by tools/generate-assets.mjs. Do not edit by hand.\n` +
    `export const ICON_CSS = ${JSON.stringify(CSS)};\n` +
    `export const ICON_SETS: Record<string, string[]> = ${JSON.stringify(sets)};\n` +
    `export const ICONS: Record<"glow" | "crisp", Record<string, string>> = ${JSON.stringify(icons)};\n`,
);

mkdirSync("backdrops", { recursive: true });
for (const b of BACKDROPS) for (const m of ["light", "dark"]) writeFileSync(`backdrops/${b.key}-${m}.svg`, b.fn(m === "dark"));
console.log(`icons: ${Object.keys(icons.glow).length} per style; backdrops: ${BACKDROPS.length * 2}`);
